import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const outputJson = path.join(root, 'problems', 'leetcode-index.json');
const outputJs = path.join(root, 'problems', 'leetcode-index.js');
const checkOnly = process.argv.includes('--check');
const buildOnly = process.argv.includes('--build');
const pageSize = 100;

const globalQuery = `
query problemsetQuestionList($categorySlug: String, $limit: Int, $skip: Int, $filters: QuestionListFilterInput) {
  problemsetQuestionList: questionList(categorySlug: $categorySlug limit: $limit skip: $skip filters: $filters) {
    totalNum
    data {
      questionFrontendId
      title
      titleSlug
      difficulty
      isPaidOnly
      topicTags { name slug }
    }
  }
}`;

const chinaQuery = `
query problemsetQuestionList($categorySlug: String, $limit: Int, $skip: Int, $filters: QuestionListFilterInput) {
  problemsetQuestionList(categorySlug: $categorySlug limit: $limit skip: $skip filters: $filters) {
    total
    questions {
      frontendQuestionId
      title
      titleCn
      titleSlug
      difficulty
      paidOnly
      topicTags { name nameTranslated slug }
    }
  }
}`;

const difficultyMap = { Easy: '基础', Medium: '进阶', Hard: '高级' };

function validate(snapshot) {
  if (!snapshot || !snapshot.meta || !Array.isArray(snapshot.questions)) {
    throw new Error('Invalid LeetCode index snapshot');
  }
  if (snapshot.meta.indexedTotal !== snapshot.questions.length) {
    throw new Error('LeetCode index count does not match metadata');
  }
  const slugs = new Set();
  for (const question of snapshot.questions) {
    if (!question.id || !question.slug || !question.title || !question.url) {
      throw new Error(`Incomplete LeetCode entry: ${question.slug || question.id || 'unknown'}`);
    }
    if (slugs.has(question.slug)) throw new Error(`Duplicate LeetCode slug: ${question.slug}`);
    if (!Object.values(difficultyMap).includes(question.difficulty)) {
      throw new Error(`Unknown difficulty for ${question.slug}`);
    }
    slugs.add(question.slug);
  }
}

function writeSnapshot(snapshot) {
  const json = `${JSON.stringify(snapshot, null, 2)}\n`;
  const js = `// Generated by scripts/sync-leetcode-index.mjs. Metadata only; problem statements stay on LeetCode.\nwindow.LEETCODE_INDEX = ${JSON.stringify(snapshot)};\n`;
  fs.writeFileSync(outputJson, json);
  fs.writeFileSync(outputJs, js);
}

async function request(url, query, variables, attempt = 1) {
  try {
    const response = await fetch(url, {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        referer: url.includes('.cn') ? 'https://leetcode.cn/problemset/' : 'https://leetcode.com/problemset/',
        'user-agent': 'Algorithm-Atlas-Metadata-Sync/1.0',
      },
      body: JSON.stringify({ query, variables }),
    });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const payload = await response.json();
    if (payload.errors?.length) throw new Error(payload.errors.map((item) => item.message).join('; '));
    return payload.data;
  } catch (error) {
    if (attempt >= 4) throw error;
    await new Promise((resolve) => setTimeout(resolve, attempt * 750));
    return request(url, query, variables, attempt + 1);
  }
}

async function fetchPages(url, query, readPage, readTotal) {
  const variables = (skip) => ({ categorySlug: '', skip, limit: pageSize, filters: {} });
  const first = await request(url, query, variables(0));
  const total = readTotal(first);
  const offsets = [];
  for (let skip = pageSize; skip < total; skip += pageSize) offsets.push(skip);
  const pages = [readPage(first)];
  for (let start = 0; start < offsets.length; start += 5) {
    const batch = offsets.slice(start, start + 5);
    const results = await Promise.all(batch.map((skip) => request(url, query, variables(skip))));
    pages.push(...results.map(readPage));
  }
  return { total, items: pages.flat() };
}

if (checkOnly || buildOnly) {
  const snapshot = JSON.parse(fs.readFileSync(outputJson, 'utf8'));
  validate(snapshot);
  const expectedJs = `// Generated by scripts/sync-leetcode-index.mjs. Metadata only; problem statements stay on LeetCode.\nwindow.LEETCODE_INDEX = ${JSON.stringify(snapshot)};\n`;
  if (buildOnly) {
    fs.writeFileSync(outputJs, expectedJs);
  } else if (fs.readFileSync(outputJs, 'utf8') !== expectedJs) {
    throw new Error('problems/leetcode-index.js is out of date');
  }
  console.log(`${buildOnly ? 'Built' : 'Verified'} ${snapshot.questions.length} LeetCode index entries`);
} else {
  const global = await fetchPages(
    'https://leetcode.com/graphql/',
    globalQuery,
    (data) => data.problemsetQuestionList.data,
    (data) => data.problemsetQuestionList.totalNum,
  );
  const china = await fetchPages(
    'https://leetcode.cn/graphql/',
    chinaQuery,
    (data) => data.problemsetQuestionList.questions,
    (data) => data.problemsetQuestionList.total,
  );
  const chinaBySlug = new Map(china.items.filter((item) => item.titleSlug).map((item) => [item.titleSlug, item]));
  const questions = global.items.map((item) => {
    const translated = chinaBySlug.get(item.titleSlug);
    const translatedTags = new Map((translated?.topicTags || []).map((tag) => [tag.slug, tag.nameTranslated || tag.name]));
    return {
      id: item.questionFrontendId,
      slug: item.titleSlug,
      title: translated?.titleCn || item.title,
      titleEn: item.title,
      difficulty: difficultyMap[item.difficulty],
      premium: Boolean(item.isPaidOnly),
      tags: item.topicTags.map((tag) => translatedTags.get(tag.slug) || tag.name),
      url: `https://leetcode.cn/problems/${item.titleSlug}/`,
    };
  }).sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true }));
  const difficulty = Object.fromEntries(Object.values(difficultyMap).map((name) => [name, questions.filter((item) => item.difficulty === name).length]));
  const snapshot = {
    meta: {
      source: 'LeetCode public problemset GraphQL',
      sourceUrl: 'https://leetcode.com/problemset/',
      fetchedAt: new Date().toISOString().slice(0, 10),
      reportedTotal: global.total,
      indexedTotal: questions.length,
      translatedTotal: questions.filter((item) => item.title !== item.titleEn).length,
      difficulty,
      notice: '仅收录题号、标题、难度、标签与原站链接，不复制题面、样例或解答。',
    },
    questions,
  };
  validate(snapshot);
  writeSnapshot(snapshot);
  console.log(`Synced ${questions.length} LeetCode entries; ${snapshot.meta.translatedTotal} have Chinese titles`);
}
